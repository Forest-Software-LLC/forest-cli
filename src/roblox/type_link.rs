//! Type re-export pass ("type linker"), run at the end of every Roblox
//! install.
//!
//! Luau does not propagate `export type` declarations through a module that is just `return require(...)`
//! The solution here is to re-export the types in all link/pointer modules.
//! 
//! DELIBERATE DESIGN DECISION:
//! On the ingest of mirrored packages, we dont export types in our link files because this would require significant backfilling if something changes.
//! Implementing the export logic CLI side gives us flexibility to iterate our solution over time. 
//!
//! ```lua
//! --Pointer file generated by Forest Package Manager.
//! local MODULE = require(script.Parent['X'])
//! export type Foo<T = any?> = MODULE.Foo<T>
//! return MODULE
//! ```
//!
//! Every link in a chain gets the FINAL module's export list, so types flow
//! hop by hop no matter which link is visited first. Rewrites are
//! deterministic and idempotent; a link whose target exports nothing is
//! normalized to the plain `return require(...)` form. A file the pass
//! cannot understand is left exactly as generated and that link's types stay
//! broken, the install itself never fails.

use std::collections::{HashMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};

use crate::roblox::plan::POINTER_HEADER;

/// First-line prefix of every mirror-generated link kind
const MIRROR_HEADER_PREFIX: &str = "--Generated by the forest ";

/// Local the rewritten link binds its target to. Luau only re-exports types
/// through a local assigned directly from a require() call.
const LOCAL_NAME: &str = "MODULE";

/// This is not a max depth check, but instead how many individual module hops (links) we allow before considering it a cycle.
/// (If you've got more than 32 genuine module hops please reach out)
const MAX_CHAIN: usize = 32;

/// Walk the mount and patch every generated link file with explicit type
/// re-exports. Infallible by design: problems are per-file warnings.
pub fn relink_types(mount: &Path) {
    let mut cache: HashMap<PathBuf, Option<Vec<ExportedType>>> = HashMap::new();
    walk(mount, &mut cache);
}

fn walk(dir: &Path, cache: &mut HashMap<PathBuf, Option<Vec<ExportedType>>>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        // Same exemption as install cleanup: `_`/`.` entries (probably) aren't ours.
        if name.starts_with('_') || name.starts_with('.') { //NOTE: Does anyone start their lua modules files with _? If you do and you see this open an issue.
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            walk(&path, cache);
        } else if name.ends_with(".lua") || name.ends_with(".luau") { //NOTE: Should we start force converting files to .luau?
            relink_file(&path, cache);
        }
    }
}

fn relink_file(path: &Path, cache: &mut HashMap<PathBuf, Option<Vec<ExportedType>>>) {
    let Ok(source) = fs::read_to_string(path) else { return };
    if !is_link(&source) { // Doesnt have the pointer header, skip
        return;
    }
    let Some(expr) = require_expr(&source) else { return }; // No require() found, skip

    let exports = match resolve_exports(path, &expr, cache) {
        Some(exports) => exports,
        None => {
            crate::message::warn(&format!(
                "Could not resolve types through {}; its target's exported types won't be visible.",
                path.display()
            ));
            return;
        }
    };

    let header = source.lines().next().unwrap_or_default(); // Reuse the header of the original source
    let rendered = render(header, &expr, &exports);
    if rendered != source { // No point in writing if the source is the same (less rojo freakouts)
        if let Err(e) = fs::write(path, &rendered) {
            crate::message::warn(&format!("Failed to update {}: {}", path.display(), e));
        }
    }
}

/// Is this source a forest-generated link module?
fn is_link(source: &str) -> bool {
    let first = source.lines().next().unwrap_or_default();
    first == POINTER_HEADER || first.starts_with(MIRROR_HEADER_PREFIX)
}

/// Resolve a link's target through any further links and return the final
/// real module's exported types. `None` = could not resolve; `Some(vec![])`
/// = resolved fine, target exports nothing.
fn resolve_exports(
    link_path: &Path,
    expr: &str,
    cache: &mut HashMap<PathBuf, Option<Vec<ExportedType>>>,
) -> Option<Vec<ExportedType>> {
    let (module_path, module_source) = resolve_final_module(link_path, expr)?;
    if let Some(cached) = cache.get(&module_path) {
        return cached.clone(); // Return cached exports if available
    }
    let exports = Some(extract_exports(&strip_comments(&module_source))); // Found the module, go get exports.
    cache.insert(module_path, exports.clone());
    exports
}

/// Follow the require chain from a link file to the first non-link module,
/// returning its path and source.
fn resolve_final_module(link_path: &Path, expr: &str) -> Option<(PathBuf, String)> {
    let mut current_file = link_path.to_path_buf();
    let mut current_expr = expr.to_string();
    for _ in 0..MAX_CHAIN {
        let target = resolve_one(&current_file, &current_expr)?;
        let source = fs::read_to_string(&target).ok()?;
        if !is_link(&source) {
            return Some((target, source));
        }
        current_expr = require_expr(&source)?; // ? = loud early return None
        current_file = target;
    }
    None
}

/// Extract the argument of the first `require(...)` in the source. Works on
/// both generated forms (`return require(...)` and the rewritten
/// `local MODULE = require(...)`).
fn require_expr(source: &str) -> Option<String> {
    let start = source.find("require(")? + "require(".len();
    let rest = &source[start..];
    let mut depth = 1usize;
    for (i, c) in rest.char_indices() {
        match c {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth == 0 {
                    return Some(rest[..i].trim().to_string());
                }
            }
            _ => {}
        }
    }
    None
}

// ---------------------------------------------------------------------------
// Require-chain resolution: `script…` expression -> filesystem module
// ---------------------------------------------------------------------------

enum Step {
    Parent,
    Child(String),
}

/// Parse a generated `script…` expression into instance steps. Only shapes
/// our generators emit: `.Parent`, `.Ident`, `["name"]`, `['name']`.
fn parse_steps(expr: &str) -> Option<Vec<Step>> {
    let rest = expr.strip_prefix("script")?;
    let chars: Vec<char> = rest.chars().collect();
    let mut steps = Vec::new();
    let mut i = 0;
    while i < chars.len() {
        match chars[i] {
            '.' => {
                let (ident, end) = read_ident(&chars, i + 1)?;
                i = end;
                steps.push(if ident == "Parent" { Step::Parent } else { Step::Child(ident) });
            }
            '[' => {
                i += 1;
                let quote = *chars.get(i)?;
                if quote != '"' && quote != '\'' {
                    return None;
                }
                i += 1;
                let mut name = String::new();
                loop {
                    let c = *chars.get(i)?;
                    if c == '\\' {
                        // JSON.stringify escapes (mirror shims). Anything
                        // fancier (\uXXXX) bails; the file is left alone.
                        let n = *chars.get(i + 1)?;
                        match n {
                            '\\' | '"' | '\'' | '/' => {
                                name.push(n);
                                i += 2;
                            }
                            _ => return None,
                        }
                    } else if c == quote {
                        i += 1;
                        break;
                    } else {
                        name.push(c);
                        i += 1;
                    }
                }
                if *chars.get(i)? != ']' {
                    return None;
                }
                i += 1;
                steps.push(Step::Child(name));
            }
            c if c.is_whitespace() => i += 1,
            _ => return None,
        }
    }
    Some(steps)
}

/// One require hop: map `script…` from the link file's DataModel position to
/// the filesystem. A link named init.lua(u) IS its folder (folder module:
/// `script` = the directory); any other file is itself.
fn resolve_one(link_file: &Path, expr: &str) -> Option<PathBuf> {
    let steps = parse_steps(expr)?;
    let file_name = link_file.file_name()?.to_str()?;
    let is_folder_module = file_name == "init.lua" || file_name == "init.luau";
    // `node` is the fs object backing the current Instance: a directory for
    // folders/folder-modules, a file for file modules. Parent semantics are
    // the same for both: the containing directory('s parent).
    let mut node = if is_folder_module {
        link_file.parent()?.to_path_buf()
    } else {
        link_file.to_path_buf()
    };
    for step in steps {
        node = match step {
            Step::Parent => node.parent()?.to_path_buf(),
            Step::Child(name) => child_node(&node, &name)?,
        };
    }
    // The final Instance must be a module: a file, or a folder with an init.
    if node.is_dir() {
        ["init.lua", "init.luau"] // The case where the folder is actually a module
            .iter()
            .map(|init| node.join(init))
            .find(|p| p.is_file())
    } else if node.is_file() { // Module is literally a module
        Some(node)
    } else {
        None
    }
}

/// A child Instance under a directory: a subdirectory or a `Name.lua(u)`
/// file. Pointer exprs URL-encode segment names (plan.rs) while mirror shims
/// don't — try the raw name first, then its URL-decoded form.
fn child_node(dir: &Path, name: &str) -> Option<PathBuf> {
    let mut candidates = vec![name.to_string()];
    if name.contains('%') {
        if let Ok(decoded) = urlencoding::decode(name) {
            if decoded != name {
                candidates.push(decoded.into_owned());
            }
        }
    }
    for candidate in candidates {
        let sub = dir.join(&candidate);
        if sub.is_dir() {
            return Some(sub);
        }
        for ext in ["lua", "luau"] {
            let file = dir.join(format!("{candidate}.{ext}"));
            if file.is_file() {
                return Some(file);
            }
        }
    }
    None
}

