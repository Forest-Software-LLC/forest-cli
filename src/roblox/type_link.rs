#[derive(Debug, Clone, PartialEq)]
struct ExportedType {
    name: String,
    /// Inner text of the generic parameter list (`T, U = any?`), None for a
    /// non-generic type.
    generics: Option<String>,
}

// Shared scanning primitives: every pass below walks `&[char]` with an
// index, and all string/escape handling lives in skip_string alone.

fn is_ident_char(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}

/// Read the identifier starting at chars[start]; returns it and one-past-end.
fn read_ident(chars: &[char], start: usize) -> Option<(String, usize)> {
    let mut end = start;
    while end < chars.len() && is_ident_char(chars[end]) {
        end += 1;
    }
    (end > start && !chars[start].is_ascii_digit())
        .then(|| (chars[start..end].iter().collect(), end))
}

/// One past the end of the string literal starting at chars[i] — short (`"…"` /
/// `'…'`, escape-aware) or long (`[=*[…]=*]`) — or None when chars[i] starts no
/// string. Unterminated strings run to the end of input.
fn skip_string(chars: &[char], i: usize) -> Option<usize> {
    match chars.get(i) {
        Some(&quote @ ('"' | '\'')) => {
            let mut j = i + 1;
            while j < chars.len() {
                match chars[j] {
                    '\\' => j += 2,
                    c if c == quote => return Some(j + 1),
                    _ => j += 1,
                }
            }
            Some(chars.len())
        }
        Some('[') => long_bracket_level(chars, i).map(|level| long_bracket_end(chars, i, level)),
        _ => None,
    }
}

/// Blank out comments (line and long-bracket) while leaving string literals
/// intact, so declaration scanning never matches commented-out code.
/// Newlines survive so blanked regions stay line-shaped.
fn strip_comments(src: &str) -> String {
    let chars: Vec<char> = src.chars().collect();
    let mut out = String::with_capacity(src.len());
    let mut i = 0;
    while i < chars.len() {
        if let Some(end) = skip_string(&chars, i) {
            out.extend(&chars[i..end]);
            i = end;
        } else if chars[i] == '-' && chars.get(i + 1) == Some(&'-') {
            let end = match long_bracket_level(&chars, i + 2) {
                Some(level) => long_bracket_end(&chars, i + 2, level),
                None => {
                    let mut j = i;
                    while j < chars.len() && chars[j] != '\n' {
                        j += 1;
                    }
                    j
                }
            };
            out.extend(chars[i..end].iter().map(|&c| if c == '\n' { '\n' } else { ' ' }));
            i = end;
        } else {
            out.push(chars[i]);
            i += 1;
        }
    }
    out
}

/// Is chars[i] the opening of a long bracket `[=*[`? Returns its level.
fn long_bracket_level(chars: &[char], i: usize) -> Option<usize> {
    if chars.get(i) != Some(&'[') {
        return None;
    }
    let mut j = i + 1;
    let mut level = 0;
    while chars.get(j) == Some(&'=') {
        level += 1;
        j += 1;
    }
    if chars.get(j) == Some(&'[') { Some(level) } else { None }
}

/// Index one past the closing `]=*]` of the long bracket opening at `open`,
/// or the end of input when unterminated.
fn long_bracket_end(chars: &[char], open: usize, level: usize) -> usize {
    let mut i = open + level + 2;
    while i < chars.len() {
        if chars[i] == ']' {
            let mut j = i + 1;
            let mut eq = 0;
            while chars.get(j) == Some(&'=') {
                eq += 1;
                j += 1;
            }
            if eq == level && chars.get(j) == Some(&']') {
                return j + 1;
            }
        }
        i += 1;
    }
    chars.len()
}

/// Collect `export type Name<…> =` declarations from comment-stripped source.
/// String literals survive comment stripping (singleton-type defaults need
/// them), so the scan steps over them here.
fn extract_exports(cleaned: &str) -> Vec<ExportedType> {
    let chars: Vec<char> = cleaned.chars().collect();
    let mut exports: Vec<ExportedType> = Vec::new();
    let mut seen: HashSet<String> = HashSet::new();
    let mut scan = 0; // where the keyword hunt currently is
    while scan < chars.len() {
        if let Some(string_end) = skip_string(&chars, scan) {
            scan = string_end;
            continue;
        }
        // A declaration is the sequence `export type Name`, each word at an
        // identifier boundary. Any mismatch moves the hunt forward one char.
        if chars[scan] != 'e'
            || (scan > 0 && is_ident_char(chars[scan - 1]))
            || !word_at(&chars, scan, "export")
        {
            scan += 1;
            continue;
        }
        let type_kw = skip_ws(&chars, scan + "export".len());
        if type_kw == scan + "export".len() || !word_at(&chars, type_kw, "type") {
            scan += 1;
            continue;
        }
        let name_start = skip_ws(&chars, type_kw + "type".len());
        if name_start == type_kw + "type".len() {
            scan += 1;
            continue;
        }
        let Some((name, after_name)) = read_ident(&chars, name_start) else {
            scan += 1;
            continue;
        };
        // `cursor` walks the rest of the declaration: an optional generic
        // parameter list, then the `=` that makes it a real declaration.
        let mut cursor = skip_ws(&chars, after_name);
        let generics = if chars.get(cursor) == Some(&'<') {
            match capture_generics(&chars, cursor) {
                Some((params, after_generics)) => {
                    cursor = after_generics;
                    if params.trim().is_empty() { None } else { Some(params) }
                }
                None => {
                    // Unbalanced `<…`: skip it, keep hunting.
                    scan = cursor + 1;
                    continue;
                }
            }
        } else {
            None
        };
        // Only an actual declaration (`= …` follows) counts.
        let equals_at = skip_ws(&chars, cursor);
        if chars.get(equals_at) == Some(&'=')
            && chars.get(equals_at + 1) != Some(&'=')
            && seen.insert(name.clone())
        {
            exports.push(ExportedType { name, generics });
        }
        scan = cursor;
    }
    exports
}

/// Does the identifier-boundary word `word` start at chars[i]?
fn word_at(chars: &[char], i: usize, word: &str) -> bool {
    i + word.len() <= chars.len()
        && chars[i..i + word.len()].iter().copied().eq(word.chars())
        && chars.get(i + word.len()).map_or(true, |&c| !is_ident_char(c))
}

fn skip_ws(chars: &[char], mut i: usize) -> usize {
    while i < chars.len() && chars[i].is_whitespace() {
        i += 1;
    }
    i
}

/// Capture the inner text of a balanced `<…>` starting at chars[open]. `->`
/// arrows and string literals inside (e.g. singleton-type defaults) don't
/// count toward nesting.
fn capture_generics(chars: &[char], open: usize) -> Option<(String, usize)> {
    let mut depth = 1usize;
    let mut i = open + 1;
    while i < chars.len() {
        if let Some(end) = skip_string(chars, i) {
            i = end;
            continue;
        }
        match chars[i] {
            '<' => depth += 1,
            '>' if chars[i - 1] != '-' => {
                depth -= 1;
                if depth == 0 {
                    return Some((chars[open + 1..i].iter().collect(), i + 1));
                }
            }
            _ => {}
        }
        i += 1;
    }
    None
}

/// Split on a separator at bracket depth 0 (over `<>()[]{}`), string-aware.
fn split_top_level(inner: &str, sep: char) -> Vec<String> {
    let chars: Vec<char> = inner.chars().collect();
    let mut parts = Vec::new();
    let mut current = String::new();
    let mut depth = 0usize;
    let mut i = 0;
    while i < chars.len() {
        if let Some(end) = skip_string(&chars, i) {
            current.extend(&chars[i..end]);
            i = end;
            continue;
        }
        let c = chars[i];
        match c {
            '<' | '(' | '[' | '{' => depth += 1,
            '>' if i > 0 && chars[i - 1] == '-' => {} // `->` arrow
            '>' | ')' | ']' | '}' => depth = depth.saturating_sub(1),
            _ => {}
        }
        if c == sep && depth == 0 {
            parts.push(current.trim().to_string());
            current.clear();
        } else {
            current.push(c);
        }
        i += 1;
    }
    if !current.trim().is_empty() {
        parts.push(current.trim().to_string());
    }
    parts
}

